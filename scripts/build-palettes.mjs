// Writes app/palettes.css and the themed logo files from lib/palettes.mjs.
// The original logo (public/brand/notanota-original.svg) is never changed: each variant keeps every
// path, opacity and stroke, and moves each colour by the same hue/saturation/lightness offset it had
// from the logo's main burgundy, so antialiasing and light/dark detail survive.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { PALETTES, DEFAULT_PALETTE } from '../lib/palettes.mjs';

export const LOGO_SOURCE = 'public/brand/notanota-original.svg';
export const LOGO_BASE = '#912433';

function toHsl(hex) {
  const n = parseInt(hex.slice(1), 16);
  const r = ((n >> 16) & 255) / 255, g = ((n >> 8) & 255) / 255, b = (n & 255) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s, l];
}
function toHex([h, s, l]) {
  const k = (n) => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return '#' + [f(0), f(8), f(4)].map((v) => Math.round(Math.max(0, Math.min(1, v)) * 255).toString(16).padStart(2, '0')).join('');
}
const clamp = (v) => Math.max(0, Math.min(1, v));

export function remapColour(hex, target, base = LOGO_BASE) {
  const [bh, bs, bl] = toHsl(base), [th, ts, tl] = toHsl(target), [h, s, l] = toHsl(hex);
  return toHex([(th + (h - bh) + 360) % 360, clamp(bs ? ts * (s / bs) : ts), clamp(tl + (l - bl))]);
}

export function recolourLogo(svg, target) {
  return svg.replace(/(fill|stroke)="(#[0-9a-fA-F]{6})"/g, (_, attr, hex) => `${attr}="${remapColour(hex.toLowerCase(), target)}"`);
}

const v = (name, value) => `  --${name}: ${value};`;
function block(t, dark = false) {
  const ink = dark ? '#000000' : t.foreground;
  return [
    v('background', t.background), v('background-deep', t.deep), v('surface', t.surface), v('surface-elevated', t.elevated),
    v('foreground', t.foreground), v('foreground-muted', t.muted), v('primary', t.primary), v('primary-hover', t.hover),
    v('primary-active', t.active), v('primary-foreground', t.onPrimary), v('accent', t.primary), v('accent-soft', t.soft),
    v('border', t.border), v('border-strong', t.strong), v('fx-teal', t.primary), v('fx-teal-strong', t.hover),
    v('fx-teal-soft', t.soft), v('fx-slate', t.foreground), v('nb-bordo', t.primary), v('nb-card', t.surface),
    v('nb-card-line', t.border), v('nb-ink-line', t.strong), v('nb-sticky', t.soft), v('nb-sticky-ink', t.foreground),
    v('nb-cover', t.surface), v('nb-sticker-line', t.foreground), v('nb-highlight', `${t.primary}24`),
    v('nb-staff-line', `${t.foreground}b8`), v('brand-support', t.support), v('shadow-color', `${ink}${dark ? '55' : '14'}`),
    v('shadow-1', dark ? `0 1px 2px ${ink}66, 0 8px 24px -12px ${ink}99` : `0 1px 2px ${ink}0d, 0 10px 30px -14px ${ink}2e`),
    v('shadow-2', dark ? `0 2px 6px ${ink}66, 0 24px 48px -20px ${ink}b3` : `0 2px 6px ${ink}0f, 0 24px 56px -24px ${ink}40`),
    v('surface-raised', dark ? t.elevated : t.surface), v('field', dark ? t.deep : t.deep),
  ].join('\n');
}

export async function expectedOutputs(root = new URL('../', import.meta.url)) {
  const source = await readFile(new URL(LOGO_SOURCE, root), 'utf8');
  const files = {};
  const css = ['/* Generated by scripts/build-palettes.mjs from lib/palettes.mjs. Do not edit by hand. */'];
  for (const palette of PALETTES) {
    files[`public/brand/notanota-${palette.id}.svg`] = palette.id === DEFAULT_PALETTE ? source : recolourLogo(source, palette.light.primary);
    files[`public/brand/notanota-${palette.id}-dark.svg`] = recolourLogo(source, palette.dark.primary);
    const scope = `[data-palette="${palette.id}"]`;
    const lightSel = palette.id === DEFAULT_PALETTE
      ? `html:not([data-theme=dark]):not([data-palette]), html:not([data-theme=dark])${scope}, html:not([data-theme=dark]) ${scope}`
      : `html:not([data-theme=dark])${scope}, html:not([data-theme=dark]) ${scope}`;
    const darkSel = palette.id === DEFAULT_PALETTE
      ? `html[data-theme=dark]:not([data-palette]), html[data-theme=dark]${scope}, html[data-theme=dark] ${scope}`
      : `html[data-theme=dark]${scope}, html[data-theme=dark] ${scope}`;
    css.push(`${lightSel} {\n${block(palette.light)}\n}`);
    css.push(`${darkSel} {\n${block(palette.dark, true)}\n}`);
  }
  // Previews can pin a palette to light or dark whatever the page uses (data-mode on the scope).
  for (const palette of PALETTES) {
    const scope = `[data-palette="${palette.id}"]`;
    css.push(`html [data-mode="light"]${scope} {\n${block(palette.light)}\n}`);
    css.push(`html [data-mode="dark"]${scope} {\n${block(palette.dark, true)}\n}`);
  }
  // A scoped preview carries its own ground, ink and type, and the matching logo file.
  css.push('[data-palette-scope] { background: var(--background); color: var(--foreground); }');
  css.push('[data-mode="dark"] .brand-logo-light, [data-mode="light"] .brand-logo-dark { display: none !important; }');
  css.push('[data-mode="dark"] .brand-logo-dark, [data-mode="light"] .brand-logo-light { display: block !important; }');
  files['app/palettes.css'] = css.join('\n\n') + '\n';
  return files;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const root = new URL('../', import.meta.url);
  await mkdir(new URL('public/brand/', root), { recursive: true });
  for (const [path, content] of Object.entries(await expectedOutputs(root))) await writeFile(new URL(path, root), content);
  console.log('palettes.css and logo variants written');
}
