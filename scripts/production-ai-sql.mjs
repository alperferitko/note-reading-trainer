// Writes ONE file to paste into the SQL Editor of the PRODUCTION project (aywgulopittrbkkbwjwn):
// the AI ledger, score library and learning-profile migrations in order, the free trial, then the
// activation with the live-site limits. Run: node scripts/production-ai-sql.mjs  ->  out-sql/production-ai-launch.sql
// It refuses to run twice (the first statement stops if the AI ledger already exists).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const pins = JSON.parse(readFileSync(join(root, 'supabase/ai-staging-target.json'), 'utf8'));
const MIGRATIONS = [
  '202610300001_ai_usage_ledger.sql',
  '202611020001_ai_usage_settlement_reconcile.sql',
  '202611030001_ai_usage_in_flight_concurrency.sql',
  '202611040001_score_library.sql',
  '202611040002_learning_profile_reports.sql',
  '202611040003_learning_week_plan.sql',
  '202611040004_ai_free_trial.sql',
];

// Live-site limits. Per request at most 0.02 USD is reserved (the gateway's bound); a usual answer
// costs about 0.005 USD. Per account: 6 a minute, 25 a day (0.20 USD), 60 and 0.50 USD for the whole
// 3-day trial. For everyone together: 5 USD a day and 30 USD in total, after which NotaNota AI pauses.
const ACTIVATE = `
update ai_private.control set
  enabled = true, project_ref = '${pins.productionProjectRef}',
  requests_per_minute = 6, requests_per_day = 25, max_concurrent = 1, max_request_micro = 20000,
  user_daily_micro = 200000,
  trial_days = 3, trial_launch_at = now(), trial_user_requests = 60, trial_user_micro = 500000,
  global_daily_micro = 5000000, global_total_micro = 30000000
where id;
select enabled, project_ref, trial_days, trial_launch_at, requests_per_day, trial_user_requests,
  global_daily_micro / 1e6 as global_daily_usd, global_total_micro / 1e6 as global_total_usd from ai_private.control;
`;

const guard = `-- NotaNota AI launch for the PRODUCTION project ${pins.productionProjectRef}. Generated by scripts/production-ai-sql.mjs.
-- Paste the whole file into Supabase > (production project) > SQL Editor and press Run once.
-- Comments below that say "staging only" / "never production" date from before the launch decision of 2026-11-04.
do $guard$ begin
  if to_regclass('ai_private.control') is not null then raise exception 'NotaNota AI tables already exist here: nothing was changed.'; end if;
end $guard$;
`;
const parts = MIGRATIONS.map(name => `\n-- ===== ${name} =====\n${readFileSync(join(root, 'supabase/migrations', name), 'utf8')}`);
mkdirSync(join(root, 'out-sql'), { recursive: true });
const out = join(root, 'out-sql', 'production-ai-launch.sql');
writeFileSync(out, `${guard}${parts.join('\n')}\n-- ===== activation =====${ACTIVATE}`);
console.log(`wrote ${out}`);
