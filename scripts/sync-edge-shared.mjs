// Copies the two files the ai-gateway needs from outside supabase/functions/ into it, so the
// Edge bundle never imports beyond its own folder. Run after editing either source;
// tests/edge-bundle.test.mjs fails while a copy is stale.
import { readFile, writeFile } from 'node:fs/promises';

export const VENDOR_HEADER = '// GENERATED by scripts/sync-edge-shared.mjs from lib/practice-evidence.mjs. Do not edit; edit the source and re-run.\n';
export const TARGET_HEADER = '// GENERATED by scripts/sync-edge-shared.mjs from supabase/ai-staging-target.json. Do not edit; edit the source and re-run.\n';

export async function expectedCopies(root = new URL('../', import.meta.url)) {
  const evidence = await readFile(new URL('lib/practice-evidence.mjs', root), 'utf8');
  const target = JSON.parse(await readFile(new URL('supabase/ai-staging-target.json', root), 'utf8'));
  return {
    'supabase/functions/_shared/vendor/practice-evidence.mjs': VENDOR_HEADER + evidence,
    'supabase/functions/_shared/ai/staging-target.mjs': `${TARGET_HEADER}export default Object.freeze(${JSON.stringify(target, null, 2)});\n`,
  };
}

import { pathToFileURL } from 'node:url';
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = new URL('../', import.meta.url);
  for (const [path, content] of Object.entries(await expectedCopies(root))) {
    await writeFile(new URL(path, root), content);
    console.log(`wrote ${path}`);
  }
}
